import { expect, test } from "@playwright/test";
import { createLocalAccount } from "./localAccount";
import { ownProfileSchema } from "../../src/lib/profiles/schemas";

test("contacts consent, list invitations and monthly reading persist for real accounts", async ({ page, browser }) => {
  test.setTimeout(180000);
  const otherContext = await browser.newContext();
  const other = await otherContext.newPage();
  try {
    await createLocalAccount(page, "Calendar host");
    await createLocalAccount(other, "Calendar guest");
    const profileResponse = await other.request.post("/api/repository", { data: { op: "directory" } });
    expect(profileResponse.ok()).toBe(true);
    const guest = ownProfileSchema.parse(await profileResponse.json());
    await page.getByRole("link", { name: "Contacts", exact: true }).click();
    await page.getByLabel("Username", { exact: true }).fill(guest.username);
    await page.getByRole("button", { name: "Add contact", exact: true }).click();
    await expect(page.getByRole("status").filter({ hasText: "Contact request sent." })).toBeVisible();
    await other.goto("/contacts");
    await other.getByRole("button", { name: "Accept", exact: true }).click();
    await expect(other.getByRole("button", { name: "Accept", exact: true })).toHaveCount(0);
    await expect(other.getByText("Connected", { exact: true })).toBeVisible();
    await page.reload();
    await page.getByLabel("List name", { exact: true }).fill("My reading list");
    await page.getByRole("checkbox", { name: /Calendar guest/ }).check();
    await page.getByRole("button", { name: "Create contact list", exact: true }).click();
    await expect(page.getByRole("listitem").filter({ hasText: /^My reading list \(1\)/ })).toBeVisible();
    await page.getByRole("link", { name: "Calendar", exact: true }).click();
    const profile = await page.request.post("/api/repository", { data: { op: "profile" } });
    const { timezone } = await profile.json() as { timezone: string };
    const { formatInTimeZone } = await import("date-fns-tz");
    const future = new Date(Date.now() + 86400000);
    const startsAt = formatInTimeZone(future, timezone, "yyyy-MM-dd'T'10:00");
    const endsAt = formatInTimeZone(future, timezone, "yyyy-MM-dd'T'11:30");
    await page.getByLabel("Title", { exact: true }).fill("Read together from calendar");
    await page.getByLabel("Start date and time", { exact: true }).fill(startsAt);
    await page.getByLabel("End date and time", { exact: true }).fill(endsAt);
    await page.getByRole("checkbox", { name: "Contact list: My reading list", exact: true }).check();
    await page.getByRole("button", { name: "Schedule a session", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Read together from calendar", exact: true })).toBeVisible();
    await expect(page.getByRole("article").filter({ has: page.getByRole("heading", { name: "Read together from calendar", exact: true }) }).getByLabel("Share session link", { exact: true })).toHaveValue(/\/rooms\/[a-f0-9-]{36}$/);
    await page.reload();
    await page.getByTestId(`calendar-day-${startsAt.slice(0, 10)}`).click();
    await expect(page.getByRole("heading", { name: "Read together from calendar", exact: true })).toBeVisible();
    await other.goto("/calendar");
    await other.getByTestId(`calendar-day-${startsAt.slice(0, 10)}`).click();
    await other.getByRole("button", { name: "Accept", exact: true }).click();
    await expect(other.getByRole("button", { name: "Accept", exact: true })).toHaveCount(0);
    await expect(other.getByRole("button", { name: "Decline invitation", exact: true })).toBeVisible();
    await other.reload();
    await other.getByTestId(`calendar-day-${startsAt.slice(0, 10)}`).click();
    await expect(other.getByRole("button", { name: "Accept", exact: true })).toHaveCount(0);
    await expect(other.getByRole("button", { name: "Decline invitation", exact: true })).toBeVisible();
    const sessionResponse = await page.request.post("/api/repository", { data: { op: "start", input: { plannedMinutes: 5, themeSlug: "rain-desk", task: "Reading", companions: { mode: "solo", characterSlugs: [] } } } });
    expect(sessionResponse.ok()).toBe(true);
    const session = await sessionResponse.json() as { id: string; startedAt: string };
    await page.goto(`/session/${session.id}`);
    await page.getByRole("button", { name: "Share session", exact: true }).click();
    await expect(page.getByLabel("Share session link", { exact: true })).toHaveValue(/\/invite\/[a-f0-9]{64}$/);
    const activeResponse = await page.request.post("/api/repository", { data: { op: "active" } });
    expect((await activeResponse.json()).startedAt).toBe(session.startedAt);
    await page.getByRole("button", { name: "Finish", exact: true }).click();
    await expect(page).toHaveURL(/\/complete$/);
    await page.goto("/calendar");
    const today = formatInTimeZone(new Date(), timezone, "yyyy-MM-dd");
    await expect(page.getByTestId(`calendar-day-${today}`)).toContainText(/\d+[smh]/);
    await page.setViewportSize({ width: 375, height: 812 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  } finally { await otherContext.close(); }
});
