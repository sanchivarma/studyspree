import { expect, test } from "@playwright/test";
import { createLocalAccount } from "./localAccount";
import { characterSlugs } from "../../src/types/characters";

test("a real account mixes human and virtual tiles in one twenty-tile pager", async ({ page }) => {
  test.setTimeout(120000);
  await page.route("**/api/rooms/token", route => route.fulfill({ status: 503, json: {} }));
  await createLocalAccount(page, "Layout reader");
  const roomResponse = await page.request.post("/api/community", { data: { operation: "mutate", command: { action: "room.create", data: { title: "Layout study room", body: "Reading together", category: "deep", private: false, capacity: 4 } } } });
  expect(roomResponse.ok()).toBe(true);
  const { id } = await roomResponse.json();
  await page.goto(`/rooms/${id}`);
  await page.getByRole("button", { name: "Join", exact: true }).click();
  await expect(page.getByRole("button", { name: "Finish", exact: true })).toBeVisible();
  const response = await page.request.post("/api/repository", { data: { op: "active" } });
  const original = await response.json();
  const update = await page.request.post("/api/repository", { data: { op: "companions", id: original.id, companions: { mode: "mixed", characterSlugs: [...characterSlugs] } } });
  expect(update.ok()).toBe(true);
  await page.reload();
  const grid = page.getByTestId("room-video-grid");
  await expect(grid.locator(":scope > [data-tile-id]")).toHaveCount(20);
  await page.getByRole("button", { name: "Next page", exact: true }).click();
  await expect(grid.locator(":scope > [data-tile-id]")).toHaveCount(4);
  await page.getByRole("button", { name: "Remove Andre", exact: true }).click();
  await expect(grid.locator(":scope > [data-tile-id]")).toHaveCount(3);
  await page.getByRole("button", { name: "Previous page", exact: true }).click();
  await page.getByRole("button", { name: "Hide Layout reader from my view", exact: true }).click();
  await expect(grid.locator("[data-person-id]")).toHaveCount(0);
  await page.getByRole("button", { name: "Room controls", exact: true }).click();
  await page.getByRole("button", { name: "Restore hidden people", exact: true }).click();
  await page.keyboard.press("Escape");
  await expect(grid.locator("[data-person-id]")).toHaveCount(1);
  await page.getByRole("button", { name: "Pin my video first", exact: true }).click();
  await expect(grid.locator(":scope > [data-tile-id]").first()).toHaveAttribute("data-tile-id", /^person:/);
  expect(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight)).toBe(true);
  const currentResponse = await page.request.post("/api/repository", { data: { op: "active" } });
  expect(await currentResponse.json()).toMatchObject({ id: original.id, startedAt: original.startedAt });
  await page.getByRole("button", { name: "Finish", exact: true }).click();
  await expect(page).toHaveURL(/\/complete$/);
});
