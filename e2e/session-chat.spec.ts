import { expect, test } from "@playwright/test";
import { signIn, startSession } from "./sessionFixtures";

test("the left chat icon opens a right drawer and Escape preserves the session", async ({ page }) => {
  await signIn(page); const path = await startSession(page);
  const original = await page.evaluate(() => JSON.parse(localStorage.getItem("ss_sessions")!)[0]);
  const trigger = page.getByRole("button", { name: "Session chat", exact: true });
  expect((await trigger.boundingBox())!.x).toBeLessThan(60);
  await trigger.click();
  const drawer = page.getByRole("dialog", { name: "Session chat", exact: true });
  await expect(drawer).toBeVisible();
  const box = await drawer.boundingBox();
  expect(box!.x + box!.width).toBe(await page.evaluate(() => innerWidth));
  await expect(drawer.getByRole("heading", { name: "Your space for study notes", exact: true })).toBeVisible();
  await drawer.getByRole("textbox", { name: "Add a note", exact: true }).fill("Review this example after the session.");
  await drawer.getByRole("button", { name: "Send", exact: true }).click();
  await expect(drawer.getByRole("article")).toContainText("Review this example after the session.");
  await expect(drawer.getByRole("link")).toHaveCount(0);
  await expect(drawer.getByRole("button", { name: "People", exact: true })).toHaveCount(0);
  await page.keyboard.press("Escape");
  await expect(drawer).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await expect(page).toHaveURL(path);
  const current = await page.evaluate(() => JSON.parse(localStorage.getItem("ss_sessions")!)[0]);
  expect(current.startedAt).toBe(original.startedAt);
  expect(current.endedAt).toBeNull();
  await expect(page.getByRole("button", { name: "Copy link", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Choose companions", exact: true }).click();
  const picker = page.getByRole("dialog", { name: "Study companions", exact: true });
  await expect(picker).toBeVisible();
  await expect(picker.getByRole("button", { name: "People", exact: true })).toHaveCount(0);
  await expect(picker.getByRole("link")).toHaveCount(0);
});
